-- Document lines kept their order only by chance: ids are random, so lines could come back shuffled on screen and on
-- the PDF a customer receives. Each line now gets a running number in the order it was written, and lines sort by it.
DO $$ DECLARE t TEXT; BEGIN
  FOREACH t IN ARRAY ARRAY['invoice_lines','bill_lines','quote_lines','recurring_invoice_lines','credit_note_lines','purchase_order_lines'] LOOP
    EXECUTE format('ALTER TABLE %I ADD COLUMN line_no BIGINT GENERATED BY DEFAULT AS IDENTITY', t);
  END LOOP;
END $$;
